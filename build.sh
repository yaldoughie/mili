#!/usr/bin/env bash
# mili build - concatenate src/* into a single dist/mili.sh, inject version,
# run bash -n (+ shellcheck if present), emit sha256.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="$ROOT/src"
OUT="$ROOT/dist/mili.sh"
VERSION="${1:-$(cat "$ROOT/VERSION" 2>/dev/null || echo 0.1.0)}"

LIBS=(ui log sys state sysctl ports fw svc features fetch cores pair socks xui watchdog doctor optimize backup)

mkdir -p "$ROOT/dist"
tmp="$(mktemp)"

{
  echo '#!/usr/bin/env bash'
  echo "# mili $VERSION - single-file build (do not edit; generated by build.sh)"
  echo "# Source: https://github.com/yaldoughie/mili"
  echo 'MILI_BUNDLED=1'
  echo
  # libraries
  for l in "${LIBS[@]}"; do
    echo "# ===== lib/$l.sh ====="
    grep -vE '^#!' "$SRC/lib/$l.sh"
    echo
  done
  # tunnel modules (sorted)
  for t in "$SRC"/tunnels/*.sh; do
    [[ -e "$t" ]] || continue
    echo "# ===== tunnels/$(basename "$t") ====="
    grep -vE '^#!' "$t"
    echo
  done
  # main (drop shebang, inject version)
  echo "# ===== main.sh ====="
  grep -vE '^#!' "$SRC/main.sh" | sed "s/@MILI_VERSION@/$VERSION/g"
} >"$tmp"

# strip CR just in case (Windows checkouts)
sed -i 's/\r$//' "$tmp"
chmod +x "$tmp"

echo "==> bash -n"
bash -n "$tmp"

if command -v shellcheck >/dev/null 2>&1; then
  echo "==> shellcheck (informational)"
  shellcheck -S warning -x "$tmp" || echo "  (shellcheck reported issues; review above)"
else
  echo "==> shellcheck not installed; skipping"
fi

mv -f "$tmp" "$OUT"
chmod +x "$OUT"
sha256sum "$OUT" | tee "$OUT.sha256"
echo "==> built $OUT ($VERSION)"
